#!/usr/bin/env python3
"""Regenerate src/icons.css and src/assets/fonts from public/links.json.

The site self-hosts a Font Awesome Free 7.3.0 subset covering exactly the
icons referenced in public/links.json. Run this after adding or changing
icon classes there:

    pip install fonttools brotli
    python3 scripts/build-icon-subset.py

Requires network access to cdn.jsdelivr.net on first run (downloads are
cached in .icon-subset-cache/).
"""
import json
import re
import subprocess
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CACHE = ROOT / ".icon-subset-cache"
FA_VERSION = "7.3.0"
FA_BASE = f"https://cdn.jsdelivr.net/npm/@fortawesome/fontawesome-free@{FA_VERSION}"
OUT_CSS = ROOT / "src/icons.css"
OUT_FONTS = ROOT / "src/assets/fonts"


def fetch(name: str, subdir: str) -> Path:
    CACHE.mkdir(exist_ok=True)
    dest = CACHE / name
    if not dest.exists():
        urllib.request.urlretrieve(f"{FA_BASE}/{subdir}/{name}", dest)
    return dest


def collect_used_icons() -> dict[str, set[str]]:
    data = json.loads((ROOT / "public/links.json").read_text())
    used = {"fa-solid": set(), "fa-regular": set(), "fa-brands": set()}
    items = [l for c in data["categories"] for l in c["links"]] + data["domains"]
    for it in items:
        parts = it["icon"].split()
        fam = next((p for p in parts if p in used), None)
        if fam:
            used[fam].update(p for p in parts if p.startswith("fa-") and p not in used)
    return used


def parse_rules(path: Path) -> dict[str, str]:
    """Map icon class names to codepoints from `--fa: "..."` rules."""
    rule_re = re.compile(r"([^{}]+)\{[^{}]*--fa:\s*\"([^\"]+)\"[^{}]*\}")
    out: dict[str, str] = {}
    for m in rule_re.finditer(path.read_text()):
        sel, raw = m.group(1), m.group(2)
        if raw.startswith("\\"):
            body = raw[1:].rstrip()
            cp = body.lower() if re.fullmatch(r"[0-9a-fA-F]{1,6}", body) else format(ord(body), "x")
        else:
            cp = format(ord(raw), "x")
        for s in sel.split(","):
            s = s.strip()
            if re.fullmatch(r"\.fa-[a-z0-9-]+", s):
                out.setdefault(s[1:], cp)
    return out


def main() -> None:
    OUT_FONTS.mkdir(parents=True, exist_ok=True)
    classic = parse_rules(fetch("fontawesome.css", "css"))
    brands = parse_rules(fetch("brands.css", "css"))
    used = collect_used_icons()

    lines: list[str] = []
    missing: list[str] = []
    cps: dict[str, set[str]] = {"solid": set(), "regular": set(), "brands": set()}
    for fam, names in used.items():
        src = brands if fam == "fa-brands" else classic
        key = fam.split("-")[1]
        for name in sorted(names):
            cp = src.get(name)
            if cp is None and fam == "fa-brands" and name in classic:
                # Upstream all.css defines letter icons (e.g. .fa-n) in the
                # classic sheet; with the Brands family the browser falls back
                # to a system glyph. Emit the rule but keep the glyph out of
                # the Brands subset so rendering matches upstream exactly.
                lines.append(f'.{name} {{\n  --fa: "\\{classic[name]}";\n}}')
                continue
            if cp is None:
                missing.append(f"{fam} {name}")
                continue
            lines.append(f'.{name} {{\n  --fa: "\\{cp}";\n}}')
            cps[key].add(cp)
    if missing:
        print("warning: icons without upstream definitions:", missing)

    faces = []
    for key, srcfile, family, weight in [
        ("solid", "fa-solid-900.woff2", "Font Awesome 7 Free", 900),
        ("regular", "fa-regular-400.woff2", "Font Awesome 7 Free", 400),
        ("brands", "fa-brands-400.woff2", "Font Awesome 7 Brands", 400),
    ]:
        if not cps[key]:
            continue
        out = OUT_FONTS / srcfile
        uni = ",".join("U+" + c for c in sorted(cps[key]))
        subprocess.run(
            ["pyftsubset", str(fetch(srcfile, "webfonts")), f"--unicodes={uni}",
             "--flavor=woff2", f"--output-file={out}"],
            check=True,
        )
        print(srcfile, out.stat().st_size, "bytes,", len(cps[key]), "glyphs")
        faces.append(
            f'@font-face {{\n  font-family: "{family}";\n  font-style: normal;\n'
            f'  font-weight: {weight};\n  font-display: block;\n'
            f'  src: url("./assets/fonts/{srcfile}") format("woff2");\n}}'
        )

    header = f"""/*!
 * Font Awesome Free {FA_VERSION} (subset) by @fontawesome - https://fontawesome.com
 * License - https://fontawesome.com/license/free (Icons: CC BY 4.0, Fonts: SIL OFL 1.1, Code: MIT License)
 * Copyright 2026 Fonticons, Inc.
 * Generated by scripts/build-icon-subset.py from public/links.json icon usage.
 */"""

    base = """
.fa-solid,
.fa-regular,
.fa-brands,
.fa {
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
  display: var(--fa-display, inline-block);
  font-family: var(--fa-family, 'Font Awesome 7 Free');
  font-feature-settings: normal;
  font-style: normal;
  font-synthesis: none;
  font-variant: normal;
  font-weight: var(--fa-style, 900);
  line-height: 1;
  text-align: center;
  text-rendering: auto;
  width: var(--fa-width, 1.25em);
}

:is(.fa-solid, .fa-regular, .fa-brands, .fa)::before {
  content: var(--fa)/"";
}

@supports not (content: ""/"") {
  :is(.fa-solid, .fa-regular, .fa-brands, .fa)::before {
    content: var(--fa);
  }
}

.fa-solid {
  --fa-style: 900;
}

.fa-regular {
  --fa-style: 400;
}

.fa-brands {
  --fa-family: 'Font Awesome 7 Brands';
  --fa-style: 400;
}
"""

    OUT_CSS.write_text(header + "\n\n" + "\n\n".join(faces) + "\n" + base + "\n" + "\n\n".join(lines) + "\n")
    print("wrote", OUT_CSS, OUT_CSS.stat().st_size, "bytes")


if __name__ == "__main__":
    main()